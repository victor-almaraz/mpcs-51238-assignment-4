// The balance simulation of the exemplar (AGENTS.md, phase 11; the campaign draft's section 14.9).
//   pnpm sim [--runs N] [--seed S] [--out FILE]
// Runs every encounter for each party size and loadout, sweeps `armor.max`, and writes a Markdown
// report (default tools/sim/REPORT.md). Seeds run from S; a fight is reproduced by its encounter,
// configuration, and seed (see run.ts).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ENCOUNTERS } from "./encounters";
import { sweep, type Config, type Summary } from "./run";

const arg = (name: string, fallback: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1]! : fallback;
};
const runs = Number(arg("runs", "50"));
const seed = Number(arg("seed", "1"));
const out = arg("out", join(process.cwd(), "tools/sim/REPORT.md"));

const pct = (x: number) => `${Math.round(x * 100)}%`;
const num = (x: number) => x.toFixed(1);
const row = (label: string, s: Summary) => `| ${label} | ${pct(s.winRate)} | ${num(s.hpLost)} | ${num(s.armorUsed)} | ${num(s.rounds)} | ${pct(s.deathsDoorRate)} | ${pct(s.deathRate)} |`;
const HEAD = "| Party | Win | HP lost | Armor used | Rounds | Death's door | Dead |\n|---|---|---|---|---|---|---|";

const lines = [
  "# Balance simulation report",
  "",
  `Generated by \`pnpm sim --runs ${runs} --seed ${seed}\`. Each row is ${runs} fights with seeds ${seed} to ${seed + runs - 1}. Characters are Cadmium fighters (10 HP, 10 AP) with the \`armor\` and \`stash\` modules. HP lost, armor used, and the death's-door and death rates are per character; rounds are combat rounds per fight.`,
  "",
  "Loadouts: `unarmored` carries a fishing knife (damage 2); `jerkin` adds a leather jerkin (3 armor); `full` adds a round shield (2 more); `axe_full` replaces the knife with a boarding axe (damage 3).",
  "",
];

const parties = [1, 2, 4];
const loadouts: Config["loadout"][] = ["unarmored", "jerkin", "full", "axe_full"];
for (const e of ENCOUNTERS) {
  lines.push(`## ${e.id}${e.required ? " (on every route)" : ""}`, "", `${e.where}. Creatures: ${e.creatures.join(", ")}.`, "", HEAD);
  for (const party of parties) for (const loadout of loadouts) lines.push(row(`${party}, ${loadout}`, sweep(e, { party, loadout, armorMax: 6 }, runs, seed)));
  lines.push("");
  process.stderr.write(`${e.id} `);
}

lines.push("## armor.max", "", "Two fighters in the `full` loadout (5 armor points) against the hardest fights, by pool maximum.", "", "| Encounter | armor.max | Win | HP lost | Armor used | Rounds | Death's door | Dead |", "|---|---|---|---|---|---|---|---|");
for (const id of ["octopus", "gallery", "rivals_waiting", "ward"]) {
  const e = ENCOUNTERS.find((x) => x.id === id)!;
  for (const armorMax of [3, 4, 6, 8]) {
    const s = sweep(e, { party: 2, loadout: "full", armorMax }, runs, seed);
    lines.push(`| ${id} | ${armorMax} | ${pct(s.winRate)} | ${num(s.hpLost)} | ${num(s.armorUsed)} | ${num(s.rounds)} | ${pct(s.deathsDoorRate)} | ${pct(s.deathRate)} |`);
  }
}
lines.push("");

lines.push("## Octopus hit points", "", "The great octopus is a Quest boss (10 HP). Every route passes it, so it decides whether one character can finish.", "", "| HP | Party | Win | HP lost | Armor used | Rounds | Death's door | Dead |", "|---|---|---|---|---|---|---|---|");
const octopus = ENCOUNTERS.find((x) => x.id === "octopus")!;
for (const hp of [6, 8, 10])
  for (const [party, loadout] of [[1, "unarmored"], [1, "full"], [2, "unarmored"]] as const) {
    const s = sweep({ ...octopus, override: { hp } }, { party, loadout, armorMax: 6 }, runs, seed);
    lines.push(`| ${hp} | ${party}, ${loadout} | ${pct(s.winRate)} | ${num(s.hpLost)} | ${num(s.armorUsed)} | ${num(s.rounds)} | ${pct(s.deathsDoorRate)} | ${pct(s.deathRate)} |`);
  }
lines.push("");
writeFileSync(out, lines.join("\n"));
process.stderr.write(`\nwrote ${out}\n`);
