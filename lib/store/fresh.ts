// One script that rebuilds the database from nothing (supabase/reset.sql, then every migration in name
// order), inside a single transaction, for pasting into the Supabase SQL Editor. Node only.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { migrations } from "./migrations";

export const RESET = "supabase/reset.sql";

export function freshScript(root = process.cwd()): string {
  const parts = [`-- ${RESET}\n${readFileSync(join(root, RESET), "utf8")}`, ...migrations(root).map((m) => `-- supabase/migrations/${m.name}\n${m.sql}`)];
  return [
    "-- Generated by `pnpm db:fresh`. Deletes every Cadmium table, function, and the Realtime policy, then",
    "-- applies every migration. One transaction: if any statement fails, nothing changes.",
    "begin;",
    ...parts,
    "commit;",
    "",
  ].join("\n\n");
}
